// Optional release signing. Create a keystore.properties file (kept out of VCS)
// with storeFile / storePassword / keyAlias / keyPassword to sign release builds.
// See scripts/make-keystore.sh and docs/BUILD.md.
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) keystorePropsFile.inputStream().use { load(it) }
}

